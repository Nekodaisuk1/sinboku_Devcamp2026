import {readFile, writeFile} from 'node:fs/promises';

const source = new URL('../../wireframe/data/knowledge.json', import.meta.url);
const output = new URL('../../supabase/seed.sql', import.meta.url);
const knowledge = JSON.parse(await readFile(source, 'utf8'));
const rows = knowledge.resources.filter(item => item.reviewStatus === 'published').map(item => ({
  stable_key: item.id, name: item.name, summary: item.summary, url: item.url, source_name: item.source,
  checked_on: item.checkedOn, category: item.category, kind: item.kind, online: item.online, free: item.free,
  prefecture: item.prefecture, grades: item.grades, domains: item.domains, verbs: item.verbs, conditions: item.conditions,
  reason: item.reason, first_step: item.step, deadline: item.deadline
}));
const literal = JSON.stringify(rows).replaceAll("'", "''");
const sql = [
  '-- Generated by: npm --prefix service run catalog:seed',
  `-- Source: wireframe/data/knowledge.json (${rows.length} published resources)`,
  '',
  'with source_rows as (',
  `  select * from jsonb_to_recordset('${literal}'::jsonb) as item(`,
  '    stable_key text, name text, summary text, url text, source_name text, checked_on date, category text, kind text,',
  '    online boolean, free boolean, prefecture text, grades jsonb, domains jsonb, verbs jsonb, conditions jsonb,',
  '    reason text, first_step text, deadline text',
  '  )',
  '), inserted_resources as (',
  '  insert into public.resources (stable_key)',
  '  select stable_key from source_rows',
  '  on conflict (stable_key) do nothing',
  '  returning id, stable_key',
  '), all_resources as (',
  '  select id, stable_key from public.resources where stable_key in (select stable_key from source_rows)',
  '), versions as (',
  '  insert into public.resource_versions (resource_id, version, status, name, summary, url, source_name, checked_on, category, kind, online, free, prefecture, grades, domains, verbs, conditions, reason, first_step, deadline)',
  "  select r.id, 1, 'published', s.name, s.summary, s.url, s.source_name, s.checked_on, s.category, s.kind, s.online, s.free, s.prefecture, s.grades, s.domains, s.verbs, s.conditions, s.reason, s.first_step, nullif(s.deadline, '')",
  '  from source_rows s join all_resources r using (stable_key)',
  '  where not exists (select 1 from public.resource_versions v where v.resource_id = r.id and v.version = 1)',
  '  returning id, resource_id',
  ')',
  'update public.resources r',
  'set published_version_id = v.id',
  'from versions v',
  'where r.id = v.resource_id and r.published_version_id is null;',
  ''
].join('\n');
await writeFile(output, sql);
console.log(`Generated ${rows.length} catalog rows at ${output.pathname}`);
